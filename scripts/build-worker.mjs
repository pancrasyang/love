import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const target='worker/dashboard-worker.mjs';
const image=readFileSync('worker/src/image-type.mjs','utf8');
const source=readFileSync('worker/src/index.mjs','utf8');
const dependency="import {inspectImage,MAX_BYTES} from './image-type.mjs';\n";
assert(source.startsWith(dependency),'Worker dependency changed; update dashboard bundling');
const main=source.slice(dependency.length);
assert(!/^import\s/m.test(image+main),'Dashboard bundle cannot have external imports');
const helpers=image.replace(/^export const MAX_BYTES=/m,'const MAX_BYTES=').replace(/^export function inspectImage\(/m,'function inspectImage(');
assert(!/^export\s/m.test(helpers),'Unexpected helper export; update dashboard bundling');
const output='// Generated by node scripts/build-worker.mjs. Edit worker/src instead.\n'+helpers+'\n'+main;
if(process.argv.includes('--check')){
 assert.equal(readFileSync(target,'utf8'),output,'Rebuild the dashboard Worker bundle');
 console.log('Dashboard Worker matches source');
}else{
 writeFileSync(target,output);
 console.log('Wrote '+target);
}
